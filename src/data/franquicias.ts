export const sectorLabel = (s: SectorFranquicia) => SECTORES.find((x) => x.id === s)!.label

export function formatInversion(n: number | null): string {
  if (n === null) return 'A consultar'
  return n.toLocaleString('es-ES') + ' €'
}

