export type SectorFranquicia =
  | 'viajes'
  | 'salud'
  | 'formacion'
  | 'retail'
  | 'hosteleria'
  | 'servicios'
  | 'automocion'
  | 'inmobiliaria'

export interface Franquicia {
  slug: string
  nombre: string
  sector: SectorFranquicia
  actividad: string
  inversion: number | null // euros, orientativa
  aportePropio: number | null // capital de bolsillo que suele pedirse, orientativo
  unidades: number | null
  descripcion: string[]
  incluye: string[]
  encaja: string[]
  revisar: string[]
}

